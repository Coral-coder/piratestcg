// Writes docs/coverage.md: how much of each pack the engine models.
// The masked pack is reported by card number only, never by name.
import fs from 'node:fs';
import { BUILTIN_CARDS, withPack } from '../src/data';
import { IMPLEMENTED, isCovered, type CardDef } from '../src/engine';

const masked = withPack(JSON.parse(fs.readFileSync('public/packs/forbidden-paradise.json', 'utf8')), 'forbidden-paradise');

function missing(c: CardDef): string[] {
  const out = [...(c.unsupported ?? [])];
  for (const e of c.effects) if (!IMPLEMENTED.has(e.code)) out.push(e.code);
  return [...new Set(out)];
}

function section(title: string, cards: CardDef[], showNames: boolean): string {
  const kinds = ['ship', 'crew', 'treasure'] as const;
  let md = `## ${title}\n\n| Kind | Cards | Fully modelled | Partial |\n|---|---|---|---|\n`;
  let all = 0;
  let ok = 0;
  for (const k of kinds) {
    const cs = cards.filter((c) => c.kind === k);
    const cov = cs.filter(isCovered).length;
    all += cs.length;
    ok += cov;
    md += `| ${k} | ${cs.length} | ${cov} | ${cs.length - cov} |\n`;
  }
  md += `| **all** | **${all}** | **${ok} (${Math.round((ok / all) * 100)}%)** | ${all - ok} |\n\n`;
  const partial = cards.filter((c) => !isCovered(c));
  if (partial.length) {
    md += '<details><summary>Partial cards</summary>\n\n| Card | Missing |\n|---|---|\n';
    for (const c of partial) md += `| ${c.id}${showNames ? ' ' + c.name : ''} | ${missing(c).join(', ')} |\n`;
    md += '\n</details>\n\n';
  }
  return md;
}

let md = '# Coverage\n\nGenerated by `npm run coverage-report`. A card is *fully modelled* when every part of its text maps to an effect the engine implements. Partial cards can still be played; the unmodelled parts are ignored.\n\n';
md += section('Original Fleets', BUILTIN_CARDS.filter((c) => c.pack === 'original'), true);
md += section('Spanish Main (2004)', BUILTIN_CARDS.filter((c) => c.pack === 'spanish-main'), true);
md += section('Forbidden Paradise pack (opt-in; names withheld here)', masked, false);
md += `## Effects implemented\n\n${[...IMPLEMENTED].sort().map((c) => '`' + c + '`').join(', ')}\n`;
fs.writeFileSync('docs/coverage.md', md);
